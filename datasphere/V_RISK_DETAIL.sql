SELECT t.*, a.ACCOUNT_TYPE, a.OPEN_DATE, m.MERCHANT_CATEGORY, m.MERCHANT_REGION,
y.TYPE_NAME, COALESCE(r.REVIEW_COUNT,0) AS REVIEW_COUNT,
COALESCE(r.REVIEW_STATUS,'NOT_REVIEWED') AS REVIEW_STATUS
FROM TRANSACTION_RISK t
JOIN ACCOUNTS a ON t.ACCOUNT_ID=a.ACCOUNT_ID
JOIN MERCHANTS m ON t.MERCHANT_ID=m.MERCHANT_ID
JOIN TRANSACTION_TYPES y ON t.TYPE_ID=y.TYPE_ID
LEFT JOIN (SELECT TRANSACTION_ID, COUNT(*) AS REVIEW_COUNT, MAX(REVIEW_STATUS) AS REVIEW_STATUS
FROM REVIEWS GROUP BY TRANSACTION_ID) r ON t.TRANSACTION_ID=r.TRANSACTION_ID
